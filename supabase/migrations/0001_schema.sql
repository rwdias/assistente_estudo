-- Study Rats — schema inicial (Supabase/Postgres)
--
-- Segurança (deny-by-default):
--   * anon: nenhum acesso a nada — o app exige login para tudo.
--   * authenticated: acesso apenas via políticas de RLS por operação.
--   * Toda função SECURITY DEFINER usa SET search_path = ''.
--   * perfis (quota de IA): usuário só lê a própria linha; escrita apenas
--     pela função consumir_quota_ia (definer) e pelo trigger de signup.

-- =========================================================
-- Tabelas
-- =========================================================

create table public.perfis (
  user_id uuid primary key references auth.users (id) on delete cascade,
  ia_chamadas_data date,
  ia_chamadas_contagem integer not null default 0,
  created_at timestamptz not null default now()
);

create table public.materias (
  id bigint generated by default as identity primary key,
  usuario_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  nome varchar(150) not null,
  descricao text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint uq_materia_por_usuario unique (usuario_id, nome)
);
create index ix_materias_usuario_id on public.materias (usuario_id);

create table public.subdivisoes (
  id bigint generated by default as identity primary key,
  materia_id bigint not null references public.materias (id) on delete cascade,
  nome varchar(150) not null,
  descricao text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint uq_subdivisao_por_materia unique (materia_id, nome)
);
create index ix_subdivisoes_materia_id on public.subdivisoes (materia_id);

create table public.perguntas (
  id bigint generated by default as identity primary key,
  subdivisao_id bigint not null references public.subdivisoes (id) on delete cascade,
  enunciado text not null,
  dificuldade varchar(50) not null,
  origem varchar(50),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index ix_perguntas_subdivisao_id on public.perguntas (subdivisao_id);

create table public.opcoes (
  id bigint generated by default as identity primary key,
  pergunta_id bigint not null references public.perguntas (id) on delete cascade,
  texto text not null,
  correta boolean not null default false,
  ordem integer not null,
  created_at timestamptz not null default now()
);
create index ix_opcoes_pergunta_id on public.opcoes (pergunta_id);

create table public.revisoes_perguntas (
  id bigint generated by default as identity primary key,
  pergunta_id bigint not null unique references public.perguntas (id) on delete cascade,
  vezes_respondida integer not null default 0,
  vezes_acertada integer not null default 0,
  vezes_errada integer not null default 0,
  ultima_resposta_correta boolean,
  ultima_respondida_em timestamptz,
  proxima_revisao_em timestamptz,
  intervalo_dias integer not null default 0,
  fator_facilidade integer not null default 250,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- =========================================================
-- Trigger: cria o perfil (quota de IA) em todo signup
-- =========================================================

create function public.criar_perfil()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.perfis (user_id) values (new.id)
  on conflict (user_id) do nothing;
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.criar_perfil();

