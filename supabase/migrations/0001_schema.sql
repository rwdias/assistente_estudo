-- SM-2 (porta fiel de src/srs.py): acerto q=5, erro q=2; EF com piso 1.3;
-- progressão 1 -> 6 -> round(intervalo * EF); erro zera o intervalo e
-- reagenda para +10 minutos. SECURITY INVOKER: o RLS acima garante que só
-- o dono da pergunta encontra/atualiza a linha de revisão.
create function public.registrar_resposta(p_pergunta_id bigint, p_correta boolean)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  r public.revisoes_perguntas%rowtype;
  q integer;
  novo_ef numeric;
  novo_intervalo integer;
  proxima timestamptz;
begin
  select * into r
  from public.revisoes_perguntas
  where pergunta_id = p_pergunta_id
  for update;

  if not found then
    raise exception 'Pergunta não encontrada.';
  end if;

  q := case when p_correta then 5 else 2 end;
  novo_ef := greatest(
    (r.fator_facilidade / 100.0) + (0.1 - (5 - q) * (0.08 + (5 - q) * 0.02)),
    1.3
  );

  if q < 3 then
    novo_intervalo := 0;
    proxima := now() + interval '10 minutes';
  else
    if r.intervalo_dias <= 0 then
      novo_intervalo := 1;
    elsif r.intervalo_dias = 1 then
      novo_intervalo := 6;
    else
      novo_intervalo := round(r.intervalo_dias * novo_ef)::integer;
    end if;
    proxima := now() + make_interval(days => novo_intervalo);
  end if;

  update public.revisoes_perguntas set
    vezes_respondida = r.vezes_respondida + 1,
    vezes_acertada = r.vezes_acertada + (case when p_correta then 1 else 0 end),
    vezes_errada = r.vezes_errada + (case when p_correta then 0 else 1 end),
    ultima_resposta_correta = p_correta,
    ultima_respondida_em = now(),
    fator_facilidade = round(novo_ef * 100)::integer,
    intervalo_dias = novo_intervalo,
    proxima_revisao_em = proxima,
    updated_at = now()
  where pergunta_id = p_pergunta_id;

  return jsonb_build_object(
    'intervalo_dias', novo_intervalo,
    'proxima_revisao_em', proxima,
    'vezes_respondida', r.vezes_respondida + 1,
    'vezes_acertada', r.vezes_acertada + (case when p_correta then 1 else 0 end),
    'ultima_resposta_correta', p_correta
  );
end;
$$;

-- Resumo por matéria para o dashboard (porta de resumo_materias).
create function public.resumo_materias()
returns table (id bigint, nome varchar, total_perguntas bigint, devidas_revisao bigint)
language sql
security invoker
set search_path = ''
stable
as $$
  select
    m.id,
    m.nome,
    count(p.id) as total_perguntas,
    count(p.id) filter (
      where rp.proxima_revisao_em is null or rp.proxima_revisao_em <= now()
    ) as devidas_revisao
  from public.materias m
  left join public.subdivisoes s on s.materia_id = m.id
  left join public.perguntas p on p.subdivisao_id = s.id
  left join public.revisoes_perguntas rp on rp.pergunta_id = p.id
  where m.usuario_id = (select auth.uid())
  group by m.id, m.nome
  order by m.nome asc;
$$;

-- Quota diária de IA (porta de verificar_e_incrementar_quota_ia).
-- SECURITY DEFINER porque o usuário NÃO tem permissão de escrita em perfis;
-- search_path fixado vazio contra hijack.
create function public.consumir_quota_ia(p_limite integer)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := (select auth.uid());
  v_contagem integer;
  v_data date;
begin
  if v_uid is null then
    return false;
  end if;

  insert into public.perfis (user_id) values (v_uid)
  on conflict (user_id) do nothing;

  select ia_chamadas_contagem, ia_chamadas_data
  into v_contagem, v_data
  from public.perfis
  where user_id = v_uid
  for update;

  if v_data is distinct from current_date then
    v_contagem := 0;
  end if;

  if v_contagem >= p_limite then
    update public.perfis
    set ia_chamadas_data = current_date, ia_chamadas_contagem = v_contagem
    where user_id = v_uid;
    return false;
  end if;

  update public.perfis
  set ia_chamadas_data = current_date, ia_chamadas_contagem = v_contagem + 1
  where user_id = v_uid;

  return true;
end;
$$;

